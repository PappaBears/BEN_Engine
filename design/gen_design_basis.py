"""Writes design/DESIGN_BASIS.md from the configuration model and the layout engine.

Run after gen_drawings.py (it embeds design/drawings/INTERFERENCE_CHECKS.md).
"""
from __future__ import annotations

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import layout as L  # noqa: E402
from revision import REV  # noqa: E402

DATE = REV["issue_date"]   # design/REVISION.json


def main():
    lays = {t: L.resolve(t) for t in L.TIER_GEOMETRY}
    o = []
    A = o.append
    A("# BEN Engine — Engineering design basis")
    A("")
    A(f"Issue {REV['drawing_rev']}, {DATE} (drawing set {REV['set_label']}; revision from `design/REVISION.json`). Generated by `design/gen_design_basis.py` from `software/ben_engine/config.py` (presets, profile `ai_inference`, climate `temperate` unless a table says otherwise) and `design/layout.py`. "
      "Numbers in tables come from the configuration model or from the layout engine; text states the rule used. Where a value is an assumption it is marked **(assumption)** and belongs on the risk list.")
    A("")
    A("## 1. Scope and codes")
    A("")
    A("The design basis covers the enclosure, the interior layout, the envelope, the structure, power, cooling, controls and life safety of the five tiers. "
      "Codes and standards referenced: ISO 668 / ISO 1496-1 / CSC (containers), ASCE 7-22 (wind, seismic, snow), AISC 360 (steel), NEC 2023 (NFPA 70) incl. 110.26, 250, 645, 706; NFPA 75 / 76, NFPA 2001 (clean agent), IFC 1207 (batteries), UL 9540 / 9540A, UL 60335-2-40 (A2L refrigerant), ASHRAE TC 9.9 thermal guidelines (A1–A3), ASHRAE 90.4, EN 13501-1 (PIR reaction to fire), ISO 9223 (corrosion), IEC 60529 (IP rating). The compliance matrix `docs/COMPLIANCE.md` maps each to a feature and a verification.")
    A("")
    # ------------------------------------------------------------------ loads
    A("## 2. Loads")
    A("")
    A("### 2.1 Dead and live loads (from the configuration rule and the layout)")
    A("")
    A("| Tier | Tare kg | Payload kg (config) | Gross kg | Per corner post kN (static) | Row strip UDL kN/m² | Rack foot point load kN |")
    A("|---|---|---|---|---|---|---|")
    for t, lay in lays.items():
        d = lay.d
        racks = lay.by_kind("rack")
        strip = next((c.value for c in lay.checks if c.id == "I-C16"), float("nan"))
        A(f"| {d['tier_label']} | {d['geometry']['tare_kg']} | {d['payload_kg']} | {d['gross_kg']} | {d['gross_kg'] * 9.81 / 4 / 1000:.1f} | {strip if strip == strip else '—'} | {(racks[0].kg if racks else 400) * 9.81 / 4 / 1000:.2f} |")
    A("")
    A("Live load inside the unit: 2.5 kN/m² on the aisle (one technician with a rack lifter and a 100 kg module) **(assumption)**. Container floors are rated for a 5460 kg forklift axle test (ISO 1496-1) and about 20 kN/m² uniform payload; rack point loads are spread by the C100 floor channels on the cross members (S-001).")
    A("")
    A("### 2.2 Environmental loads by climate package (ASCE 7 basic wind from CLIMATE_DESIGN; seismic and snow are site values)")
    A("")
    A("| Climate | Design temp °C (0.4 %) | Min temp °C | Solar W/m² | Corrosion ISO 9223 | Basic wind m/s | qz kPa (0.613·V²) | Overturning check 40 ft, 2.9 m high | Seismic | Snow |")
    A("|---|---|---|---|---|---|---|---|---|---|")
    for k, c in L.CLIMATE_DESIGN.items():
        qz = 0.613 * c["wind_ms"] ** 2 / 1000
        # wind on long side of a 40 ft HC: A = 12.192 x 2.896, Cf ~ 1.3, lever 1.45 m vs restoring W/2 x 2.438 m
        F = qz * 1.3 * 12.192 * 2.896
        Mo = F * 1.448
        Mr = lays["ben500"].d["gross_kg"] * 9.81 / 1000 * 1.219
        A(f"| {c['label']} | {c['t_design_c']} | {c['t_min_c']} | {c['solar_w_m2']} | {c['corrosion']} | {c['wind_ms']} | {qz:.2f} | F {F:.0f} kN, Mo {Mo:.0f} kNm vs Mr {Mr:.0f} kNm → {'tie-downs required' if Mo > Mr * 0.67 else 'stable, tie-downs still required'} | site SDS; Detail B option ≥ 0.5 g | roof 300 kg/m² rating; site ground snow |")
    A("")
    A("All tiers are anchored at the four bottom corner castings (twist-locks, SITE-002) regardless of the overturning result; BEN 5 is anchored with 4 × M16 wedge anchors (S-001 Detail A). Seismic: the container shell is a rigid box; interior racks are the governing non-structural component (ASCE 7 Ch. 13, Ip = 1.5 for a facility that must stay operational). Detail B on S-001 gives the top-of-rack strut option; the engineer of record confirms per site SDS.")
    A("")
    # ------------------------------------------------------------------ structure
    A("## 3. Container structural notes")
    A("")
    A("- **Corner posts and castings.** ISO 1496-1 stacking test: 86.4 t per corner post pair (9-high, 1.8 g). BEN loads are 1–4 t per post; the posts are not the limiting element. Lifting is by the top castings only (4-leg spreader, sling angle ≥ 60°); tie-down by the bottom castings. Never lift a loaded unit by the bottom castings or fork pockets (CTP-S4, HOLD).")
    A("- **Cutouts.** The corrugated side walls are shear panels. Every cutout (roof line-set curbs, end-wall pipe sleeves, power and fibre entries, floor drain) gets a welded 50 × 50 × 5 reinforcement frame (CTP-A1, HOLD, certified welder). No cutout within 300 mm of a corner post; the sum of cutout widths in any 1 m of wall stays below 400 mm or a diagonal stiffener is added. Roof curbs sit between roof bows.")
    A("- **CSC.** Any structural modification voids the CSC plate. A modified container is re-inspected by an approved surveyor and re-plated or put on an ACEP programme before road or sea transport (CTP-A2, HOLD). Units that never travel by sea still need the inspection for crane lifting insurance.")
    A("- **Floor.** Original 28 mm plywood on 122 × 45 C-section cross members at ~300 mm. Two C100 × 50 × 5 channels run under the row, through-bolted M12 at every cross member (85 N·m). Racks and cabinets bolt to the channels, never to plywood alone.")
    A("- **Corrosion.** Exterior coating C4-M minimum; C5-M for the `coastal` package (ISO 9223 class C5). All cut edges primed within 4 h. Dissimilar-metal contact (aluminium brand panel on Corten) isolated with EPDM tape.")
    A("- **Transport.** Battery at 30–50 % SoC, dangerous-goods paperwork; racks blocked; IT removed or strapped; traps drained. Gross mass weighed and recorded (CTQ-A3).")
    A("")
    # ------------------------------------------------------------------ thermal envelope
    A("## 4. Thermal envelope and condensation control")
    A("")
    R = 0.1 / 0.022
    U = 1 / (R + 0.17)
    A(f"- Wall and roof: 100 mm PIR (λ 0.022 W/mK) → R {R:.1f} m²K/W centre of panel, U {U:.2f} W/m²K. The configuration uses an effective R of 3.5 m²K/W to account for thermal bridging at corner posts, door frame and cross members (about 25 % penalty) **(assumption, to be validated by the first thermal survey)**.")
    A("- Floor: 80 mm PIR + 18 mm plywood + 2 mm anti-static vinyl (R ≈ 3.8). Doors: 25 mm PIR + liner + secondary EPDM bulb seal.")
    A("- Vapour control: the sealed steel liner is the warm-side vapour barrier. Interior design point 22 °C / 50 % RH, dew point 11.1 °C.")
    A("")
    A("| Climate | t_min °C | Liner surface temp at t_min °C (centre of panel) | Margin to dew point K | Thermal bridge surface est. °C | Action |")
    A("|---|---|---|---|---|---|")
    for k, c in L.CLIMATE_DESIGN.items():
        tsi = 22 - U * 0.13 * (22 - c["t_min_c"])
        tb = 22 - 0.13 / (0.13 + 0.03 + 0.04) * (22 - c["t_min_c"])  # 20 mm closed-cell + steel + film (rough)
        act = "20 mm closed-cell on steel; heated door gasket" if c["t_min_c"] <= -20 else ("20 mm closed-cell on exposed steel" if c["t_min_c"] < 5 else "standard")
        A(f"| {c['label']} | {c['t_min_c']} | {tsi:.1f} | {tsi - 11.1:.1f} | {tb:.0f} | {act} |")
    A("")
    A("Envelope heat gain at design (config rule, kW): " + ", ".join(f"{lay.d['tier_label']} {lay.d['envelope_gain_kw']}" for lay in lays.values()) + " — small against the IT load but it sets the no-load cooling floor and the condensation risk at the hot plenum wall. Fire: PIR class B-s2,d0 (EN 13501-1) or FM 4880 approved; the liner protects the foam.")
    A("")
    # ------------------------------------------------------------------ acoustics, egress, lighting
    A("## 5. Acoustics")
    A("")
    A("Source levels **(assumptions from vendor-typical data)**: in-row DX unit 65 dB(A) at 1 m, roof condenser 58 dB(A) at 10 m, dry cooler 62 dB(A) at 10 m, rack fans 70 dB(A) in the hot plenum. Inside the aisle expect 72–78 dB(A) at full load: hearing protection for stays over 2 h (post the sign). Outside, with the shell and PIR giving about 30 dB attenuation, the governing sources are the condensers / dry cooler; place them on the side away from receptors and allow 10 m to a property line for 55 dB(A) night-time limits. A site-specific noise assessment is required where the setback is less than 10 m.")
    A("")
    A("## 6. Egress, working space and lighting")
    A("")
    A("- Single row along the rack wall; the cold aisle is the egress path to the cargo doors. Drawn clear width " + ", ".join(f"{lay.d['tier_label']} {lay.aisle_width:.0f} mm" for lay in lays.values() if lay.is_container) + " (≥ 900 mm egress, ≥ 914 mm NEC 110.26 condition 1). Cargo doors open outward 270° and are fitted with inside panic releases **(add to BOM: FS-050)**. Dead-end length equals the container length; under NFPA 75 a single exit is acceptable for a room this size with occupancy limited to service staff.")
    A("- NEC 110.26 condition 2 (1067 mm) is not met and is not required: the surface opposite the row is the insulated liner with no exposed grounded conductive parts at working height; the opposing-wall items (EPO, FRP) are ≤ 100 mm deep and above/below the 914 mm zone or within 600 mm of the door. If a customer places grounded equipment on the aisle wall, condition 2 applies and fails — this is a design constraint written on A-002.")
    A("- Working space width 762 mm is satisfied by the continuous aisle; height 2.0 m is satisfied (tray underside 2250 mm).")
    A("- Lighting: LED 4000 K luminaires over the aisle at the ceiling, 500 lx at 1 m AFF on the rack faces, emergency light at the door (90 min). Lights on PNL-M with a controller relay output (relay2) for remote control.")
    A("")
    # ------------------------------------------------------------------ power / cooling / controls basis
    A("## 7. Power, cooling and controls basis (from the configuration rules)")
    A("")
    A("| Tier | IT kW | Racks | kW/rack | Voltage | Service A (calc / breaker) | UPS | Battery kWh | Cooling (config → drawn) | Units drawn | Airflow cfm | PUE est. | Config row_length_mm / fits |")
    A("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for t, lay in lays.items():
        d = lay.d
        drawn = lay.notes.get("cooling_resolved", lay.cfg.cooling)
        units = []
        n_air = lay.notes.get("n_air", 0)
        if lay.tier == "ben5":
            units.append(f"{d['cooling_units_total']} × cabinet DX 5.8 kW")
        if n_air:
            units.append(f"{n_air} × in-row 300 / 20 kW")
        if drawn == "rdhx_drycooler":
            units.append(f"{lay.notes.get('n_rdhx')} × RDHx + {lay.notes.get('n_pu')} row CDU + dry cooler")
        if drawn == "dlc_cdu":
            units.append(f"{lay.notes.get('n_cdu')} × CDU + dry cooler")
        A(f"| {d['tier_label']} | {lay.cfg.it_kw:.0f} | {lay.cfg.racks} | {d['per_rack_kw']} | {d['voltage']} | {d['service_amps_calc']} / {d['service_breaker_a']} | {d['ups_modules']} × {d['ups_kva_each']} kVA | {d['battery_kwh']} | {lay.cfg.cooling} → {drawn} | {'; '.join(units)} | {d['airflow_cfm']} | {d['pue_estimate']} | {d['row_length_mm']} / {d['row_fits']} |")
    A("")
    A("Rules: UPS carries IT only with 15 % headroom; service sized at 80 % continuous; cooling N units at 1.05 × IT with 1.5 %/K DX derate above 35 °C; DLC removes 75 % of rack heat at the cold plate, the rest is air **(assumption)**; airflow 125 cfm/kW air-cooled, 40 cfm/kW liquid. Controls (docs/CONTROLS_HARDWARE_DECISION.md): BEN Controls Pro (PLCnext AXC F 2152 + Axioline F I/O in a UL 508A panel, OnLogic Karbon 400 edge computer) on BEN 150/500, BEN Controls Lite (Revolution Pi RevPi Connect 4 + DIO/AIO) on BEN 5, selectable on BEN 30; BEN Pods on BEN Mesh (Thread, MGM240P): two per rack (cold and hot face) + room + outdoor, BEN 5 3; logical node ids one per two racks; three inlet probes per rack (0.4 / 1.2 / 1.8 m; 0.3 / 0.7 / 1.1 m in the BEN 5), one outlet probe, supply/return probes, RH, dP across the containment, leak rope, door contact, utility pulse — identical to `Twin.sensors()` and `spec/PROTOCOL.md`.")
    A("")
    # ------------------------------------------------------------------ interference
    A("## 8. Interference checks (generated)")
    A("")
    A("The layout engine places the row and checks it against the enclosure. The table is generated by `design/drawings/gen_drawings.py` and is also printed per tier in each `INDEX.md`. "
      "Result key: **OK** passes; **OK\\*** passes with the resolution stated; **FAIL** does not pass as given — the resolution column says what was changed on the drawings or what must change in the configuration.")
    A("")
    p = os.path.join(HERE, "drawings", "INTERFERENCE_CHECKS.md")
    if os.path.exists(p):
        txt = open(p).read()
        body = txt.split("\n", 3)[-1] if txt.startswith("#") else txt
        A(body.strip())
    else:
        A(L.checks_table(list(lays.values())))
        A("")
        A("### Deviations applied")
        A("")
        A(L.deviations_md(list(lays.values())))
    A("")
    A("### Summary of what the checks found (after the 2026-11-08 configuration update)")
    A("")
    A("1. **Two-row layouts do not fit any container tier** (2 × 1070 + 1000 = 3140 > 2200). All tiers use a single row against one wall; the aisle is 930 mm.")
    A("2. **Presets now fit as given.** `config.derived()['row_fits']` is true for every preset and the layout engine agrees: BEN 30 (3 × 300 mm in-row 20 kW, 100 mm spare), BEN 150 (5 RDHx racks + 2 row CDUs, 450 mm spare), BEN 500 (10 racks + 2 CDUs + 4 residual-air in-row units + UPS + 2 battery cabinets, 950 mm spare). No cooling fallback is applied on this set.")
    A("3. **Interior height** 2490 (config) vs 2488 computed: within the 10 mm tolerance. BEN 500 48U racks (2200) leave 290 mm to the ceiling, 10 mm short of the 300 mm rule → lights over the aisle; alternative 47U racks.")
    A("4. **As-purchased footprints (new checks I-C21 / I-C22).** The catalog quantity rules do not fit the rows: BEN 30 `PWR-UPS-93PM50` towers (2 × 495 mm) → row 3090 > 2200; BEN 150 `PWR-UPS-GVS100` × 4 + `PWR-BATT-LI` × 2 → 7484 > 5250; BEN 500 × 6 + × 4 → 13926 > 11350. Drawings use rack-mount 20 kVA modules in R1 (BEN 30, new catalog item `PWR-UPS-RM20`) and one modular UPS frame per unit (BEN 150/500). `STR-RACK48` is 1200 deep → BEN 500 aisle 800 mm (< 900 egress); drawings use a 1070-deep 48U rack. These are purchasing / configuration decisions, listed in `design/assembly/ITEM_CODES_USED.md`.")
    A("5. **NEC 110.26 condition 2** (1067 mm) fails on every container tier; condition 1 (914 mm) passes with 16 mm margin. Constraint on what may be mounted on the aisle wall (§6).")
    A("6. **Door zone.** BEN 30 has 100 mm between the cargo doors and the first cooling unit; BEN 30 R1 keeps only 6U for IT after three 10U UPS modules and a 6U battery (alternative: 20 kW preset).")
    A("7. **BEN 5.** 5 kW, 2 cabinet AC units (one per long face), 9U left for IT after 2 × (4U UPS + 3U battery pack) + 1U controls shelf (RevPi); gross 1087 kg, 2.5 t forklift.")
    A("")
    A("## 9. Component footprints used (catalogue-typical, mm)")
    A("")
    A("| Key | W × D × H | kg | Note |")
    A("|---|---|---|---|")
    for k, v in L.LIB.items():
        A(f"| {k} | {v['w']} × {v['d']} × {v['h']} | {v['kg']} | {v['label']}" + (f", {v['kw']} kW" if 'kw' in v else "") + " |")
    A("")
    A("These footprints are the basis of every interference result. When purchasing selects real parts (`purchasing/bom.csv`), update `LIB` in `design/layout.py` and regenerate; any check that flips to FAIL is a design change.")
    A("")
    A("## 10. Least accurate (stated honestly)")
    A("")
    A("- Masses: the configuration payload rule is coarse (fixed kg per rack / unit); the layout item sum differs from it by up to 15 %. Rigging uses the larger.")
    A("- Breaker, conductor, transformer and line-set sizes on E-001 / M-001 are rule-of-thumb and preliminary.")
    A("- The RDHx design for BEN 150 assumes 35 kW per door at 18 °C supply water and a residual room load handled by the dry cooler loop; no residual air unit is drawn. A CFD / twin run should confirm the room stays within ASHRAE A2 without an air unit.")
    A("- Thermal bridge temperatures in §4 are a one-dimensional estimate; the floor cross-member bridge is the likely first condensation point in the `cold` package.")
    A("- Acoustic levels are vendor-typical, not measured.")
    A("- The interference engine checks footprints and a handful of clearances; it does not check door swings of equipment (UPS front doors need ~700 mm, satisfied by the aisle), service pull-out of CDU pumps, or overhead hoist paths.")
    A("")
    with open(os.path.join(HERE, "DESIGN_BASIS.md"), "w") as f:
        f.write("\n".join(o))
    print("  wrote design/DESIGN_BASIS.md")


if __name__ == "__main__":
    main()
