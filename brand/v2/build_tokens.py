#!/usr/bin/env python3
"""Generate brand/v2/tokens.css from brand/v2/tokens.json (Schreiber AI brand v2, BEN Engine Rev 2).

    python3 brand/v2/build_tokens.py          # writes brand/v2/tokens.css
    python3 brand/v2/build_tokens.py --check  # exit 1 if tokens.css is stale

Also prints the WCAG 2.x contrast ratios of the real text/ground pairs used on the
web page, the dashboard and print (recorded in web/kit/BRAND_GUIDE.md).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
T = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))


def v(path: str) -> str:
    node = T
    for k in path.split("."):
        node = node[k]
    return node["value"] if isinstance(node, dict) else node


def css() -> str:
    c = T["color"]
    lines = ["/* GENERATED by brand/v2/build_tokens.py from tokens.json. Do not edit by hand. */",
             "/* Schreiber AI brand v2 tokens, BEN Engine Rev 2. One job per color: amber is the primary button only;",
             "   status colors are for chips and alarms only; heat maps use the thermal ramp with a legend. */",
             ":root {"]
    for k, n in c["surface"].items():
        lines.append(f"  --{k}: {n['value']};" if k != "border" else f"  --border: {n['value']};")
    lines.append(f"  --night: {v('color.surface.s0')};")
    for k, n in c["signal"].items():
        lines.append(f"  --signal-{k}: {n['value']};")
    lines += [f"  --signal: {v('color.signal.400')};", f"  --deep: {v('color.signal.700')};", f"  --cobalt: {v('color.signal.600')};",
              f"  --amber: {v('color.amber.base')};", f"  --amber-hover: {v('color.amber.hover')};",
              f"  --amber-pressed: {v('color.amber.pressed')};", f"  --on-amber: {v('color.amber.on')};",
              f"  --shop: {v('color.light.shop_white')};", f"  --paper: {v('color.light.paper')};"]
    for k in ("ink", "slate", "fog", "steel"):
        lines.append(f"  --{k}: {v('color.text.' + k)};")
    for k in ("run", "hold", "stop", "stop_light", "info"):
        lines.append(f"  --{k.replace('_', '-')}: {v('color.status.' + k)};")
    stops = c["thermal"]["stops"]
    for i, s in enumerate(stops):
        lines.append(f"  --thermal-{i}: {s['value']};")
    grad = ", ".join(f"{s['value']} {round(s['at'] * 100)}%" for s in stops)
    lines += [f"  --thermal-cool: {v('color.thermal.cool')};", f"  --thermal-warm: {v('color.thermal.warm')};",
              f"  --thermal-ramp: linear-gradient(90deg, {grad});",
              f"  --pending: {v('color.pending.chip_bg')};", f"  --pending-light: {v('color.pending.chip_bg_light')};",
              f"  --rule: {v('color.rule_line')};", f"  --rule-strong: {v('color.rule_line_strong')};"]
    f = T["font"]["family"]
    lines += [f"  --f-display: {f['display']['value']};", f"  --f-body: {f['body']['value']};", f"  --f-mono: {f['mono']['value']};"]
    for k, s in T["font"]["scale"].items():
        lines.append(f"  --t-{k}-size: {s['size_px']}px; --t-{k}-line: {s['line_px']}px; --t-{k}-weight: {s['weight']};")
        if "stretch" in s:
            lines.append(f"  --t-{k}-stretch: {s['stretch']};")
    lines.append(f"  --t-label-tracking: {T['font']['scale']['label']['tracking']};")
    lines.append(f"  --t-body-measure: {T['font']['scale']['body']['max_width']};")
    for k, r in T["radius"].items():
        lines.append(f"  --r-{k}: {r};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _lum(hexc: str) -> float:
    h = hexc.lstrip("#")
    rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a: str, b: str) -> float:
    la, lb = sorted((_lum(a), _lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


PAIRS = [
    ("Paper text on S0", "color.text.paper", "color.surface.s0"),
    ("Paper text on S2", "color.text.paper", "color.surface.s2"),
    ("Fog text on S0", "color.text.fog", "color.surface.s0"),
    ("Fog text on S2 (data plate band)", "color.text.fog", "color.surface.s2"),
    ("Steel label on S0", "color.text.steel", "color.surface.s0"),
    ("Steel label on S1", "color.text.steel", "color.surface.s1"),
    ("Steel label on S2", "color.text.steel", "color.surface.s2"),
    ("Signal Blue link on S0", "color.signal.400", "color.surface.s0"),
    ("Signal Blue on S2", "color.signal.400", "color.surface.s2"),
    ("Night Navy on Safety Amber (button)", "color.amber.on", "color.amber.base"),
    ("Night Navy on Amber hover", "color.amber.on", "color.amber.hover"),
    ("Night Navy on Amber pressed", "color.amber.on", "color.amber.pressed"),
    ("Run on S2", "color.status.run", "color.surface.s2"),
    ("Hold on S2", "color.status.hold", "color.surface.s2"),
    ("Stop on S2", "color.status.stop", "color.surface.s2"),
    ("Info on S2", "color.status.info", "color.surface.s2"),
    ("Night Navy on Hold (pending chip)", "color.surface.s0", "color.status.hold"),
    ("Ink on Shop White", "color.text.ink", "color.light.shop_white"),
    ("Slate on Shop White", "color.text.slate", "color.light.shop_white"),
    ("Deep Cobalt on Shop White", "color.signal.700", "color.light.shop_white"),
    ("Stop-light on Shop White", "color.status.stop_light", "color.light.shop_white"),
    ("Ink on pending-light chip", "color.text.ink", "color.pending.chip_bg_light"),
    ("Night Navy QR on Shop White", "color.surface.s0", "color.light.shop_white"),
]


def report() -> list:
    out = []
    for name, fg, bg in PAIRS:
        r = contrast(v(fg), v(bg))
        out.append((name, v(fg), v(bg), r, "AAA" if r >= 7 else ("AA" if r >= 4.5 else ("AA large" if r >= 3 else "fail"))))
    return out


if __name__ == "__main__":
    text = css()
    target = HERE / "tokens.css"
    if "--check" in sys.argv:
        sys.exit(0 if target.exists() and target.read_text(encoding="utf-8") == text else 1)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target.relative_to(HERE.parent.parent)}")
    for name, fg, bg, r, grade in report():
        print(f"| {name} | {fg} on {bg} | {r:.2f}:1 | {grade} |")
