"""Rev 1 stays reproducible (docs/REVISION_POLICY.md rule 3).

tests/fixtures/rev1_presets.json was generated by tests/fixtures/gen_rev1_presets.py against the Rev 1 code (git 3ea7d7d) before the
Rev 2 lineup change: derived() for every Rev 1 tier x profile x climate preset, every hardening level, the forward options (dlc_hd,
dc800 both conventions) and the BEN 30 controls overrides, plus the BOM totals of each. Rev 2 must reproduce all of it exactly under
lineup="rev1", and a saved Rev 1 configuration (a dict without a ``lineup`` key) must load as rev1 and compute the same numbers.
"""
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "software"))
sys.path.insert(0, str(ROOT / "tests" / "fixtures"))

from ben_engine.config import Config, PRESETS_REV1, TIERS_BY_LINEUP, TIER_GEOMETRY  # noqa: E402
from ben_engine.bom import generate_bom, load_catalog, totals  # noqa: E402
import gen_rev1_presets as G  # noqa: E402

FIXTURE = json.loads((ROOT / "tests" / "fixtures" / "rev1_presets.json").read_text())


@pytest.fixture(scope="module")
def rebuilt():
    return G.build()


def test_fixture_covers_every_rev1_preset():
    keys = FIXTURE["derived"]
    for t in TIERS_BY_LINEUP["rev1"]:
        assert sum(1 for k in keys if k.startswith(t + "|")) >= 48, t
    assert len(keys) == 267


def test_rev1_derived_is_byte_identical(rebuilt):
    assert set(rebuilt["derived"]) == set(FIXTURE["derived"])
    for k, v in FIXTURE["derived"].items():
        assert json.dumps(rebuilt["derived"][k], sort_keys=True) == json.dumps(v, sort_keys=True), k


def test_rev1_preset_configs_unchanged(rebuilt):
    for k, v in FIXTURE["config"].items():
        assert rebuilt["config"][k] == v, k


def test_rev1_bom_totals_identical(rebuilt):
    for k, v in FIXTURE["bom"].items():
        assert rebuilt["bom"][k] == v, k


def test_presets_rev1_equal_the_frozen_presets():
    assert list(PRESETS_REV1) == ["ben5", "ben30", "ben150", "ben500", "ben2000"]
    for t, c in PRESETS_REV1.items():
        key = f"{t}|ai_inference|temperate"
        assert c.lineup == "rev1"
        assert json.loads(json.dumps(c.derived(), sort_keys=True, default=str)) == FIXTURE["derived"][key], t


def test_saved_rev1_configuration_loads_as_rev1_and_reproduces():
    """A configuration saved before Rev 2 has no lineup key: it loads as rev1 and gives the quoted numbers."""
    cat = load_catalog()
    for key in ("ben150|healthcare|hot_humid", "ben500|ai_training|cold", "ben5|private_cloud|temperate", "ben2000|ai_training|temperate"):
        saved = dict(FIXTURE["config"][key])
        assert "lineup" not in saved and "form" not in saved
        cfg = Config.from_dict(saved)
        assert cfg.lineup == "rev1" and not cfg.validate()
        assert json.loads(json.dumps(cfg.derived(), sort_keys=True, default=str)) == FIXTURE["derived"][key], key
        t = totals(generate_bom(cfg, cat))
        assert t["total_usd"] == FIXTURE["bom"][key]["total_usd"], key


def test_rev1_sample_proposal_configs_reproduce():
    """The Rev 1 sample proposals (docs/proposals/*.json) carry configs without a lineup key; they load as rev1 and their BOM total
    matches the hardware cost printed in the sample."""
    cat = load_catalog()
    for f in sorted((ROOT / "docs" / "proposals").glob("sample-*.json")):
        p = json.loads(f.read_text())
        cfg = Config.from_dict(p["config"])
        assert cfg.lineup == "rev1", f.name
        assert not cfg.validate(), f.name
        sub = Config.from_dict(p["config"]); sub.subsystems = p["headline"]["subsystems"]
        assert round(totals(generate_bom(sub, cat))["total_usd"], 2) == p["headline"]["hardware_cost_usd"], f.name


def test_rev1_lineup_rejects_rev2_tiers():
    for t in ("ben1", "ben300", "ben700"):
        with pytest.raises(ValueError):
            Config.preset(t, lineup="rev1")
        c = Config.preset(t)
        c.lineup = "rev1"
        assert any("lineup" in e for e in c.validate()), t


def test_rev1_geometry_entries_untouched():
    g = FIXTURE["derived"]["ben150|ai_inference|temperate"]["geometry"]
    assert {k: TIER_GEOMETRY["ben150"][k] for k in g} == g
    for t in TIERS_BY_LINEUP["rev1"]:
        assert "lineup" not in TIER_GEOMETRY[t] and "liquid_first" not in TIER_GEOMETRY[t], t
